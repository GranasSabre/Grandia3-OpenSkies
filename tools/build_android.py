"""Android build: writes build-android.ninja, runs ninja (NDK clang, ARM64) and packs the APK.

Usage: python tools/build_android.py [--no-apk] [target]
Result: build/android/Grandia3.apk (debug signed with toolchain/debug.keystore)

The shared runtime compiles unchanged: runtime/android/include stands in for the Windows and SSE
headers, runtime/android replaces the Windows-only files listed in EXCLUDE.
"""
import glob
import hashlib
import os
import shutil
import subprocess
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TC = os.path.join(ROOT, 'toolchain')
SDK = os.path.join(TC, 'sdk')
NDK = os.path.join(SDK, 'ndk', '29')
LLVM = os.path.join(NDK, 'toolchains', 'llvm', 'prebuilt', 'windows-x86_64', 'bin')
BT = os.path.join(SDK, 'build-tools', '35.0.1')
JAVA_HOME = os.path.join(TC, 'jdk17')
# ninja: toolchain/ninja of this checkout, else the PC port's next to it (local layout)
NINJA = next((n for n in (os.path.join(TC, 'ninja', 'ninja.exe'), os.path.join(ROOT, '..', 'port', 'toolchain', 'ninja', 'ninja.exe'))
              if os.path.exists(n)), os.path.join(TC, 'ninja', 'ninja.exe'))
TARGET = 'aarch64-linux-android28'
GLUE = os.path.join(NDK, 'sources', 'android', 'native_app_glue')

# Windows-only runtime files, replaced by runtime/android/platform_android.cpp
EXCLUDE = {
    'platform/platform.cpp', 'platform/audio.cpp', 'platform/settings.cpp', 'platform/overlay.cpp',
    'platform/pspad.cpp', 'gs/gs_gpu.cpp', 'gs/gs_texrep.cpp',
    'platform/updater.cpp',  # (PC v1.0.8: GitHub update check with WinHTTP; texrep_android.cpp replaces gs_texrep)
}


# VU1 programs (the GS pipeline thread's hot loop): test flags
VU_FLAGS = os.environ.get('G3_VU_FLAGS', '')

GLSLC = os.path.join(NDK, 'shader-tools', 'windows-x86_64', 'glslc.exe')


def build_shaders(bdir):
    """runtime/android/shaders/* -> SPIR-V arrays in build/android/gen/shaders_spv.h (SPV_<NAME>_<STAGE>)"""
    gen = os.path.join(ROOT, bdir, 'gen')
    os.makedirs(gen, exist_ok=True)
    out = os.path.join(gen, 'shaders_spv.h')
    srcs = sorted(glob.glob(os.path.join(ROOT, 'runtime', 'android', 'shaders', '*.*')))
    stamp = os.path.join(gen, 'draw_defs.txt')
    xd = os.environ.get('G3_DRAW_DEFS', '')
    if (os.path.exists(out) and all(os.path.getmtime(s) <= os.path.getmtime(out) for s in srcs)
            and os.path.exists(stamp) and open(stamp).read() == xd):
        return
    open(stamp, 'w').write(xd)
    parts = ['// generated by tools/build_android.py from runtime/android/shaders', '#pragma once', '#include <cstdint>']
    # every source once, plus extra builds with defines: (source, array name, defines)
    variants = [(s, 'SPV_' + os.path.basename(s).replace('.', '_').upper(), []) for s in srcs]
    for s in srcs:
        if os.path.basename(s) == 'draw.frag':
            variants += [(s, 'SPV_DRAW_Z_FRAG', ['-DHAS_Z=1']), (s, 'SPV_DRAW_HW_FRAG', ['-DHW']),
                         (s, 'SPV_DRAW_HW_Z_FRAG', ['-DHW', '-DHAS_Z=1'])]
        if os.path.basename(s) == 'draw_general.frag':
            variants += [(s, 'SPV_DRAW_GENERAL_Z_FRAG', ['-DHAS_Z=1'])]
    # G3_DRAW_DEFS: extra defines for the draw shader (experiments)
    xdefs = os.environ.get('G3_DRAW_DEFS', '').split()
    variants = [(s, n, d + xdefs if 'DRAW' in n and n.endswith('FRAG') else d) for s, n, d in variants]
    for s, name, defs in variants:
        spv = os.path.join(gen, name.lower() + '.spv')
        r = subprocess.run([GLSLC, '-O', '--target-env=vulkan1.1'] + defs + [s, '-o', spv], capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit('glslc failed:\n' + r.stdout + r.stderr)
        words = open(spv, 'rb').read()
        vals = ', '.join('0x%08x' % int.from_bytes(words[i:i + 4], 'little') for i in range(0, len(words), 4))
        parts.append(f'static const uint32_t {name}[] = {{{vals}}};')
    with open(out, 'w') as fh:
        fh.write('\n'.join(parts) + '\n')


def p(path):
    return os.path.relpath(path, ROOT).replace('\\', '/')


def ninja_file(bdir):
    glue = p(GLUE)
    common = (f'--target={TARGET} -O2 -fPIC -fwrapv -fno-strict-aliasing -ffp-contract=off -fsigned-char '
              f'-Iruntime/android/include -Iruntime/include -Igenerated -I{glue}')
    gen_flags = common + ' -w -Igenerated/main'
    cxx_flags = (common + ' -std=c++20 -DNOMINMAX -Wall -Wno-unused-variable -Wno-unused-function '
                 '-Wno-unused-but-set-global -Wno-unused-but-set-variable -Wno-unknown-pragmas '
                 f'-Iruntime/src -I{bdir}/gen -Ithird_party/libadrenotools/include -include runtime/android/g3_compat.h'
                 + ' ' + os.environ.get('G3_RT_FLAGS', ''))  # e.g. -gline-tables-only for profiling
    clang = os.path.join(LLVM, 'clang.exe')
    lines = [
        f'builddir = {bdir}',
        f'cc = {clang}',
        f'cxx = {os.path.join(LLVM, "clang++.exe")}',
        f'genflags = {gen_flags}',
        f'cxxflags = {cxx_flags}',
        'rule cc',
        '  command = $cc $genflags -MD -MF $out.d -c $in -o $out',
        '  depfile = $out.d',
        '  deps = gcc',
        '  description = CC $in',
        'rule cxx',
        '  command = $cxx $cxxflags $extra -MD -MF $out.d -c $in -o $out',
        '  depfile = $out.d',
        '  deps = gcc',
        '  description = CXX $in',
        'rule asm',
        f'  command = $cc --target={TARGET} -c $in -o $out',
        '  description = AS $in',
        'rule link',
        f'  command = $cxx --target={TARGET} -shared -static-libstdc++ -Wl,-u,ANativeActivity_onCreate -Wl,--no-undefined '
        '-o $out @$out.rsp -landroid -llog -laaudio -lm -ldl',
        '  rspfile = $out.rsp',
        '  rspfile_content = $in',
        '  description = LINK $out',
        'rule ar',
        f'  command = {os.path.join(LLVM, "llvm-ar.exe")} rcs $out @$out.rsp',
        '  rspfile = $out.rsp',
        '  rspfile_content = $in',
        '  description = AR $out',
    ]
    objs_gen = []
    for f in open(os.path.join(ROOT, 'generated', 'files.txt')).read().split():
        obj = f'{bdir}/gen/' + f.replace('.c', '.o')
        lines.append(f'build {obj}: cc generated/{f}')
        objs_gen.append(obj)
    for src in sorted(glob.glob(os.path.join(ROOT, 'generated', 'iop', '*.c'))):
        rel = p(src)
        obj = f'{bdir}/gen/' + rel[len('generated/'):].replace('.c', '.o')
        lines.append(f'build {obj}: cc {rel}')
        objs_gen.append(obj)
    objs = []
    for src in sorted(glob.glob(os.path.join(ROOT, 'runtime', 'src', '**', '*.cpp'), recursive=True)):
        rel = p(src)
        sub = rel[len('runtime/src/'):]
        if sub in EXCLUDE:
            continue
        obj = f'{bdir}/rt/' + sub.replace('.cpp', '.o')
        lines.append(f'build {obj}: cxx {rel}')
        if sub == 'main.cpp':
            lines.append('  extra = -Dmain=g3_main')
        objs.append(obj)
    for src in sorted(glob.glob(os.path.join(ROOT, 'runtime', 'src', '**', '*.c'), recursive=True)):
        rel = p(src)
        obj = f'{bdir}/rt/' + rel[len('runtime/src/'):].replace('.c', '.oc')
        lines.append(f'build {obj}: cc {rel}')
        objs.append(obj)
    for src in sorted(glob.glob(os.path.join(ROOT, 'generated', 'vu', '*.cpp'))):
        rel = p(src)
        obj = f'{bdir}/gen/vu/' + os.path.basename(rel).replace('.cpp', '.o')
        lines.append(f'build {obj}: cxx {rel}')
        lines.append(f'  extra = {VU_FLAGS}')
        objs.append(obj)
    for src in sorted(glob.glob(os.path.join(ROOT, 'runtime', 'android', '*.cpp'))):
        rel = p(src)
        obj = f'{bdir}/android/' + os.path.basename(rel).replace('.cpp', '.o')
        lines.append(f'build {obj}: cxx {rel}')
        objs.append(obj)
    lines.append(f'build {bdir}/android/fiber_arm64.o: asm runtime/android/fiber_arm64.S')
    objs.append(f'{bdir}/android/fiber_arm64.o')
    lines.append(f'build {bdir}/android/glue.o: cc {glue}/android_native_app_glue.c')
    objs.append(f'{bdir}/android/glue.o')
    # libadrenotools (custom GPU drivers such as Turnip, vk_dyn.cpp): its loader goes into libgrandia3.so,
    # its hook libraries are .so files of their own next to it (loaded from the native library folder)
    at = 'third_party/libadrenotools'
    lines += [f'atflags = --target={TARGET} -O2 -fPIC -I{at}/include -I{at} -I{at}/lib/linkernsbypass -I{at}/src/hook',
              'rule atcxx',
              '  command = $cxx $atflags -std=c++20 -w -c $in -o $out',
              '  description = CXX $in',
              'rule atcc',
              '  command = $cc $atflags -w -c $in -o $out',
              '  description = CC $in',
              'rule atso',
              f'  command = $cxx --target={TARGET} -shared -static-libstdc++ -Wl,--no-undefined $ldx -o $out $in -L{bdir}/lib/arm64-v8a $libs -ldl -llog -landroid',
              '  description = LINK $out']
    def atobj(src, rule):
        obj = f'{bdir}/at/' + os.path.basename(src).rsplit('.', 1)[0] + '.o'
        lines.append(f'build {obj}: {rule} {at}/{src}')
        return obj
    ns = [atobj('lib/linkernsbypass/android_linker_ns.cpp', 'atcxx'), atobj('lib/linkernsbypass/elf_soname_patcher.cpp', 'atcxx')]
    objs += [atobj('src/driver.cpp', 'atcxx'), atobj('src/bcenabler.cpp', 'atcxx')] + ns
    libdir = f'{bdir}/lib/arm64-v8a'
    hook_impl = f'{libdir}/libhook_impl.so'
    lines.append(f'build {hook_impl}: atso {atobj("src/hook/hook_impl.cpp", "atcxx")} ' + ' '.join(ns))
    hooks = [hook_impl]
    for h in ('main_hook', 'file_redirect_hook', 'gsl_alloc_hook'):
        out_so = f'{libdir}/lib{h}.so'
        lines.append(f'build {out_so}: atso {atobj(f"src/hook/{h}.c", "atcc")} | {hook_impl}')
        lines.append('  libs = -lhook_impl')
        lines.append('  ldx = -Wl,-z,global')
        hooks.append(out_so)
    lines.append('build rt: phony ' + ' '.join(o for o in objs if '/gen/' not in o))  # runtime only (quick checks)
    lines.append(f'build {bdir}/libgen.a: ar ' + ' '.join(objs_gen))
    so = f'{bdir}/lib/arm64-v8a/libgrandia3.so'
    lines.append(f'build {so}: link ' + ' '.join(objs) + f' {bdir}/libgen.a')
    lines.append(f'default {so} ' + ' '.join(hooks))
    return so, '\n'.join(lines) + '\n'


def tool(*args):
    env = dict(os.environ, JAVA_HOME=JAVA_HOME)
    env['PATH'] = os.path.join(JAVA_HOME, 'bin') + os.pathsep + env['PATH']
    r = subprocess.run(list(args), env=env, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f'{os.path.basename(args[0])} failed:\n{r.stdout}{r.stderr}')


# lang/ (translations, subtitles) goes into the APK as assets; the app copies it into its folder
# when the manifest's hash changed (platform_android.cpp extract_lang). G3_LANG_DIR overrides the source.
LANG_DIR = os.environ.get('G3_LANG_DIR') or next(
    (d for d in (os.path.join(ROOT, '..', 'port', 'build', 'release', 'lang'), os.path.join(ROOT, 'lang')) if os.path.isdir(d)),
    os.path.join(ROOT, 'lang'))  # the PC port's release folder (local layout), else lang/ of this checkout (repo)


def lang_files():
    """(path relative to lang/, absolute path) of the files to ship, sorted"""
    out = []
    if not os.path.isdir(LANG_DIR):
        return out
    for dp, dn, fn in os.walk(LANG_DIR):
        dn.sort()
        for f in sorted(fn):
            if f.endswith(('.bak', '.tmp')) or f == 'seen.tsv' or '_test' in f:
                continue
            a = os.path.join(dp, f)
            out.append((os.path.relpath(a, LANG_DIR).replace(os.sep, '/'), a))
    return out


def build_dex(bdir):
    """runtime/android/java -> classes.dex (javac + d8 of the build tools); its path"""
    out = os.path.join(ROOT, bdir, 'java')
    srcs = sorted(glob.glob(os.path.join(ROOT, 'runtime', 'android', 'java', '**', '*.java'), recursive=True))
    dex = os.path.join(out, 'classes.dex')
    if os.path.exists(dex) and all(os.path.getmtime(x) <= os.path.getmtime(dex) for x in srcs):
        return dex
    jar = os.path.join(SDK, 'platforms', 'android-35', 'android.jar')
    cls = os.path.join(out, 'classes')
    if os.path.isdir(cls):
        shutil.rmtree(cls)
    os.makedirs(cls)
    tool(os.path.join(JAVA_HOME, 'bin', 'javac.exe'), '--release', '11', '-classpath', jar, '-d', cls, *srcs)
    classes = sorted(glob.glob(os.path.join(cls, '**', '*.class'), recursive=True))
    tool(os.path.join(BT, 'd8.bat'), '--release', '--min-api', '28', '--lib', jar, '--output', out, *classes)
    return dex


# --release: signed with the release key (never in the repo): G3_KEYSTORE (path), G3_KEY_ALIAS,
# G3_KEYSTORE_PASS, G3_KEY_PASS from the environment; the manifest without android:debuggable.
# Without --release: the debug key in toolchain/ (made on the first build).
RELEASE = '--release' in sys.argv


def release_manifest(bdir):
    src = os.path.join(ROOT, 'runtime', 'android', 'AndroidManifest.xml')
    if not RELEASE:
        return src
    text = open(src, encoding='utf-8').read().replace('android:debuggable="true"', 'android:debuggable="false"')
    out = os.path.join(ROOT, bdir, 'AndroidManifest.release.xml')
    open(out, 'w', encoding='utf-8').write(text)
    return out


def pack_apk(bdir, so):
    out = os.path.join(ROOT, bdir)
    ks = os.path.join(TC, 'debug.keystore')
    if RELEASE:
        need = ['G3_KEYSTORE', 'G3_KEY_ALIAS', 'G3_KEYSTORE_PASS', 'G3_KEY_PASS']
        missing = [n for n in need if not os.environ.get(n)]
        if missing:
            sys.exit('--release needs ' + ', '.join(missing) + ' (the release key is never part of the repo)')
    elif not os.path.exists(ks):
        tool(os.path.join(JAVA_HOME, 'bin', 'keytool.exe'), '-genkeypair', '-keystore', ks, '-storepass', 'android',
             '-alias', 'androiddebugkey', '-keypass', 'android', '-keyalg', 'RSA', '-keysize', '2048',
             '-validity', '10000', '-dname', 'CN=Android Debug,O=Android,C=US')
    base = os.path.join(out, 'base.apk')
    tool(os.path.join(BT, 'aapt2.exe'), 'link', '-o', base, '--manifest',
         release_manifest(bdir),
         '-I', os.path.join(SDK, 'platforms', 'android-35', 'android.jar'))
    unaligned = os.path.join(out, 'unaligned.apk')
    with zipfile.ZipFile(base) as zi, zipfile.ZipFile(unaligned, 'w', zipfile.ZIP_DEFLATED) as zo:
        for item in zi.infolist():
            zo.writestr(item, zi.read(item.filename))
        for lib in sorted(glob.glob(os.path.join(ROOT, os.path.dirname(so), '*.so'))):  # libgrandia3.so + adrenotools hooks
            zo.write(lib, 'lib/arm64-v8a/' + os.path.basename(lib))
        zo.write(build_dex(bdir), 'classes.dex')
        files = lang_files()
        h = hashlib.sha256()
        for rel, a in files:
            data = open(a, 'rb').read()
            h.update(rel.encode() + b'\0' + hashlib.sha256(data).digest())
            zo.writestr('assets/lang/' + rel, data)
        # first line: hash of the set, then one relative path per line
        zo.writestr('assets/lang_manifest.txt', '\n'.join([h.hexdigest()] + [r for r, _ in files]) + '\n')
        print('lang:', len(files), 'files from', os.path.normpath(LANG_DIR))
    aligned = os.path.join(out, 'aligned.apk')
    tool(os.path.join(BT, 'zipalign.exe'), '-f', '-p', '4', unaligned, aligned)
    apk = os.path.join(out, 'Grandia3.apk')
    if RELEASE:
        # passwords through the environment (apksigner env:NAME), not on the command line
        tool(os.path.join(BT, 'apksigner.bat'), 'sign', '--ks', os.environ['G3_KEYSTORE'], '--ks-key-alias', os.environ['G3_KEY_ALIAS'],
             '--ks-pass', 'env:G3_KEYSTORE_PASS', '--key-pass', 'env:G3_KEY_PASS', '--out', apk, aligned)
    else:
        tool(os.path.join(BT, 'apksigner.bat'), 'sign', '--ks', ks, '--ks-pass', 'pass:android', '--key-pass', 'pass:android',
             '--out', apk, aligned)
    for f in (base, unaligned, aligned):
        os.remove(f)
    print('APK:', apk, os.path.getsize(apk) // 1024, 'KB')


def main():
    bdir = 'build/android'
    build_shaders(bdir)
    so, text = ninja_file(bdir)
    nf = os.path.join(ROOT, 'build-android.ninja')
    with open(nf, 'w') as fh:
        fh.write(text)
    targets = [a for a in sys.argv[1:] if not a.startswith('--')]
    r = subprocess.call([NINJA, '-C', ROOT, '-f', nf] + targets)
    if r != 0:
        sys.exit(r)
    if '--no-apk' not in sys.argv and not targets:
        pack_apk(bdir, so)


if __name__ == '__main__':
    main()
